"""Writes client/python/THIRD-PARTY-NOTICES and client/python-embedded/THIRD-PARTY-NOTICES: the license texts of the
Rust crates (and the C library zstd inside zstd-sys) that each Python wheel links statically.

    tools/gen-third-party.py            # rewrite the files
    tools/gen-third-party.py --check    # fail if a file is not what the lockfile gives (make test-clients runs this)

Which crates: those reachable from the crate through normal dependencies, not through a procedural macro (a
proc-macro runs in the compiler and is not linked) and not through build dependencies. The texts come from the
crates' sources in the cargo registry (`cargo metadata --offline`); a crate that is dual licensed MIT OR Apache-2.0
is taken under MIT, whose text carries the copyright line. Crates with the same text are listed together.
The audit table is docs/licenses.md.
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# file names to take, in order of preference; the dual-licensed crates are used under MIT
PREFER = ["LICENSE-MIT", "LICENSE.BSD-3-Clause", "LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING"]
# extra files inside a package: zstd-sys carries the C library, whose license is its own file
EXTRA = {"zstd-sys": [("zstd/LICENSE", "the zstd C library inside zstd-sys")]}

HEADER_NETWORK = """\
Third-party software in the tsdb Python wheel and source distribution
=====================================================================

This package, the tsdb network client for Python (module tsdb_client), is licensed under the Apache License 2.0 (the
file LICENSE next to this one; see also NOTICE). It does not contain the database engine: it talks to a tsdbd.

The extension module contains the Rust libraries listed below, and the zstd C library (compiled by the zstd-sys
crate), all linked statically. Their licenses ask that their copyright notice and license text travel with the
binary; they are reproduced here. A crate that offers MIT OR Apache-2.0 is used under MIT. Libraries that only run
at build time (the build tools, procedural macros) are not part of the wheel and are not listed.

NumPy, when installed (pip install intellistream-tsdb-client[numpy]), is a separate package and not part of this one.

docs/licenses.md in the source repository lists every dependency of tsdb.

This file is generated by tools/gen-third-party.py from client/python/Cargo.lock; do not edit it.
"""

HEADER_EMBEDDED = """\
Third-party software in the tsdb embedded Python wheel and source distribution
==============================================================================

This package (module tsdb_embedded) is licensed under the GNU Affero General Public License, version 3 only (the file
LICENSE next to this one; see also NOTICE and LICENSING.md of the source repository), except for the files of the tsdb
client libraries and headers that are compiled into it, which are under the Apache License 2.0 (LICENSES/Apache-2.0.txt).
It includes the tsdb database engine, written in C and compiled into the extension module. The network client,
intellistream-tsdb-client (Apache-2.0), is a separate package this one depends on.

The extension module also contains the Rust libraries listed below, and the zstd C library (compiled by the zstd-sys
crate), all linked statically. Their licenses ask that their copyright notice and license text travel with the
binary; they are reproduced here. A crate that offers MIT OR Apache-2.0 is used under MIT. Libraries that only run
at build time (the build tools, procedural macros) are not part of the wheel and are not listed.

NumPy, when installed, is a separate package and not part of this one.

docs/licenses.md in the source repository lists every dependency of tsdb.

This file is generated by tools/gen-third-party.py from client/python-embedded/Cargo.lock; do not edit it.
"""

# the crate directory, and the header of its notices
TARGETS = [("client/python", HEADER_NETWORK), ("client/python-embedded", HEADER_EMBEDDED)]


def metadata(crate):
    r = subprocess.run(["cargo", "metadata", "--offline", "--locked", "--format-version", "1"],
                       cwd=os.path.join(ROOT, crate), capture_output=True, text=True)
    if r.returncode:
        sys.exit("cargo metadata failed:\n" + r.stderr)
    return json.loads(r.stdout)


def linked(md):
    pk = {p["id"]: p for p in md["packages"]}
    nodes = {n["id"]: n for n in md["resolve"]["nodes"]}
    proc = {i for i, p in pk.items() if any("proc-macro" in t["kind"] for t in p["targets"])}
    seen, todo = set(), [md["resolve"]["root"]]
    while todo:
        i = todo.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            normal = any(k["kind"] is None for k in d["dep_kinds"])
            if normal and d["pkg"] not in proc:
                todo.append(d["pkg"])
    return sorted((pk[i] for i in seen if pk[i].get("source")), key=lambda p: p["name"])


def text_of(path):
    with open(path, encoding="utf-8") as f:
        return f.read().strip("\n")


def main():
    bad = False
    for crate, header in TARGETS:
        out_path = os.path.join(ROOT, crate, "THIRD-PARTY-NOTICES")
        groups = {}  # text -> [(label, license)]
        for p in linked(metadata(crate)):
            d = os.path.dirname(p["manifest_path"])
            files = [(f, "") for f in PREFER if os.path.isfile(os.path.join(d, f))][:1]
            if not files:
                sys.exit("%s %s: no license file found in %s" % (p["name"], p["version"], d))
            files += [(f, why) for f, why in EXTRA.get(p["name"], [])]
            for f, why in files:
                label = "%s %s%s" % (p["name"], p["version"].split("+")[0], " (" + why + ")" if why else "")
                groups.setdefault(text_of(os.path.join(d, f)), []).append((label, p["license"]))
        out = [header]
        for text, who in sorted(groups.items(), key=lambda kv: kv[1][0][0]):
            out.append("-" * 76)
            for label, lic in who:
                out.append("%s  [%s]" % (label, lic))
            out.append("-" * 76)
            out.append("")
            out.append(text)
            out.append("")
        result = "\n".join(out)
        if "--check" in sys.argv:
            if not os.path.exists(out_path) or open(out_path, encoding="utf-8").read() != result:
                print("%s/THIRD-PARTY-NOTICES is out of date: run tools/gen-third-party.py" % crate, file=sys.stderr)
                bad = True
            else:
                print("%s/THIRD-PARTY-NOTICES up to date (%d license texts)" % (crate, len(groups)))
        else:
            with open(out_path, "w", encoding="utf-8") as f:
                f.write(result)
            print("wrote %s (%d license texts)" % (out_path, len(groups)))
    sys.exit(1 if bad else 0)


main()
