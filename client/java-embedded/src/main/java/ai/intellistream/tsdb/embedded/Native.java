    // ------------------------------------------------------------------------------------------------ the library

    /** Where the library was loaded from, for {@link EmbeddedDb#librarySource()}. */
    static final String SOURCE;
    private static final SymbolLookup LIB;

    static {
        if (ADDRESS.byteSize() != 8)
            throw new UnsupportedOperationException("tsdb needs a 64-bit JVM");
        String[] source = new String[1];
        LIB = load(source);
        SOURCE = source[0];
        MemorySegment sym = LIB.find("tsdb_struct_size").orElseThrow(() -> new UnsatisfiedLinkError(
                "libtsdb.so (" + SOURCE + ") has no tsdb_struct_size: it is older than this binding"));
        MethodHandle size = LINKER.downcallHandle(sym, FunctionDescriptor.of(JAVA_LONG, JAVA_INT));
        checkAbi(SOURCE, k -> {
            try {
                return (long) size.invokeExact(k);
            } catch (Throwable t) {
                throw new AssertionError(t);
            }
        });
    }

    /**
     * Refuses a library whose structs differ in size from this binding's layouts: one built from other headers
     * would read or write past the end of the memory this side allocates (tsdb_options_init, tsdb_get_stats, ...),
     * which corrupts the heap instead of failing.
     */
    static void checkAbi(String source, IntToLongFunction size) {
        for (int k = 0; k < ALL_STRUCTS.length; k++) {
            long theirs = size.applyAsLong(k);
            if (theirs != ALL_STRUCTS[k].byteSize())
                throw new UnsatisfiedLinkError("libtsdb.so (" + source + ") does not match this binding: "
                        + ALL_STRUCTS[k].name().orElse("struct " + k) + " is " + theirs + " bytes there and "
                        + ALL_STRUCTS[k].byteSize() + " here; use the library this jar was built with");
        }
    }

    /**
     * Finds libtsdb.so, in this order: the system property {@code tsdb.library} or the environment variable
     * {@code TSDB_LIBRARY} (a path: what someone asked for explicitly); the copy bundled in this jar for the
     * platform (built from the same headers as this code); {@code java.library.path}; and last the dynamic linker's
     * own search ({@code LD_LIBRARY_PATH}, the ld.so cache). The bundled copy comes before java.library.path, which
     * on Linux includes /usr/lib and /lib: any libtsdb.so installed there, perhaps an older one, would win otherwise.
     */
    private static SymbolLookup load(String[] source) {
        Arena global = Arena.global();
        String explicit = System.getProperty("tsdb.library");
        if (explicit == null || explicit.isEmpty())
            explicit = System.getenv("TSDB_LIBRARY");
        if (explicit != null && !explicit.isEmpty()) {
            source[0] = explicit;
            return SymbolLookup.libraryLookup(Paths.get(explicit), global);
        }
        String name = System.mapLibraryName("tsdb");
        String resource = "native/" + platform() + "/" + name;
        try (InputStream in = Native.class.getResourceAsStream(resource)) {
            if (in != null) {
                /* extracted next to nothing else, loaded, and deleted at once: the mapping keeps it alive, and
                 * no copy is left behind even if the JVM dies */
                Path dir = Files.createTempDirectory("tsdb-native");
                Path p = dir.resolve(name);
                try {
                    Files.copy(in, p, StandardCopyOption.REPLACE_EXISTING);
                    SymbolLookup l = SymbolLookup.libraryLookup(p, global);
                    source[0] = "bundled " + resource;
                    return l;
                } finally {
                    Files.deleteIfExists(p);
                    Files.deleteIfExists(dir);
                }
            }
        } catch (IOException e) {
            throw new UncheckedIOException("cannot extract the bundled " + resource, e);
        }
        String libPath = System.getProperty("java.library.path", "");
        for (String dir : libPath.split(java.io.File.pathSeparator)) {
            if (dir.isEmpty())
                continue;
            Path p = Paths.get(dir, name);
            if (Files.isRegularFile(p)) {
                source[0] = p.toString();
                return SymbolLookup.libraryLookup(p, global);
            }
        }
        source[0] = name;
        return SymbolLookup.libraryLookup(name, global);
    }

    /** {@code linux-x86_64}, {@code linux-aarch64}, ...: the directory of the bundled library. */
    static String platform() {
        String os = System.getProperty("os.name", "").toLowerCase(Locale.ROOT);
        String arch = System.getProperty("os.arch", "").toLowerCase(Locale.ROOT);
        if (arch.equals("amd64") || arch.equals("x86-64"))
            arch = "x86_64";
        else if (arch.equals("arm64"))
            arch = "aarch64";
        return (os.startsWith("linux") ? "linux" : os.replace(' ', '_')) + "-" + arch;
    }

    private static final class UncheckedIOException extends RuntimeException {
        private static final long serialVersionUID = 1L;

        UncheckedIOException(String msg, IOException cause) {
            super(msg, cause);
        }
    }

    /** The C name and descriptor of every handle, for the test that compares them with the prototypes. */
    static final Map<String, FunctionDescriptor> BOUND = new LinkedHashMap<>();

    private static MethodHandle fn(String name, FunctionDescriptor d, Linker.Option... options) {
        BOUND.put(name, d);
        MemorySegment sym = LIB.find(name).orElseThrow(() -> new UnsatisfiedLinkError("libtsdb.so: no " + name));
        return LINKER.downcallHandle(sym, d, options);
    }

    private static FunctionDescriptor i(MemoryLayout... args) {
        return FunctionDescriptor.of(JAVA_INT, args);
    }

