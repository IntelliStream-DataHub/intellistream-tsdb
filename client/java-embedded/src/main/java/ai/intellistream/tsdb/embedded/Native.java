    /** One upcall stub per callback type for the life of the JVM; the query it serves is named by {@code ctx}. */
    static MemorySegment upcall(MethodHandles.Lookup lookup, String method, FunctionDescriptor d) {
        try {
            MethodHandle h = lookup.findStatic(lookup.lookupClass(), method, d.toMethodType());
            return LINKER.upcallStub(h, d, Arena.global());
        } catch (ReflectiveOperationException e) {
            throw new ExceptionInInitializerError(e);
        }
    }

    // ------------------------------------------------------------------------------------------------ helpers

    /** Arrays the library returned and that are not yet freed: the tests check it is back at 0. */
    static final AtomicLong OUTSTANDING = new AtomicLong();

    /** Frees an array the library returned (never NULL-checked by the caller). */
    static void free(MemorySegment p) {
        if (p.address() == 0)
            return;
        try {
            FREE.invokeExact(p);
        } catch (Throwable t) {
            throw rethrow(t);
        }
        OUTSTANDING.decrementAndGet();
    }

    /** A C string the library owns, or null for NULL. */
    static String string(MemorySegment p) {
        return p.address() == 0 ? null : p.reinterpret(Long.MAX_VALUE).getString(0);
    }

    static String strerror(int rc) {
        try {
            return string((MemorySegment) STRERROR.invokeExact(rc));
        } catch (Throwable t) {
            throw rethrow(t);
        }
    }

    /** What a downcall handle threw: only Errors and RuntimeExceptions can come out of one. */
    static RuntimeException rethrow(Throwable t) {
        if (t instanceof RuntimeException r)
            throw r;
        if (t instanceof Error e)
            throw e;
        throw new IllegalStateException(t);
    }
